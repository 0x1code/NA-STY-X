"""Deterministic factored ANF circuit for the frozen original S-box.

Vector-valued Horner factorization and common-subexpression sharing replace a
256-element secret monomial array. No lookup, secret branch or multiplication.
"""
import argparse
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / 'research/reference_cipher'))
from engine_v3 import SBOX


def coefficients(table):
    if len(table) != 256:
        raise ValueError('256 truth-table entries required')
    result = list(table)
    for bit in range(8):
        for mask in range(256):
            if mask & (1 << bit):
                result[mask] ^= result[mask ^ (1 << bit)]
    return result


def evaluate_byte(value, coeff):
    out = 0
    for mask, coefficient in enumerate(coeff):
        if value & mask == mask:
            out ^= coefficient
    return out


def circuit(coeff):
    nodes, intern = [], {}

    def expression(op, a, b):
        if op == 'xor':
            if a == ('c', 0):
                return b
            if b == ('c', 0):
                return a
            if a == b:
                return ('c', 0)
            if a[0] == b[0] == 'c':
                return ('c', a[1] ^ b[1])
        else:
            if b == ('c', 0):
                return b
            if b == ('c', 255):
                return a
        key = (op, a, b)
        if key not in intern:
            intern[key] = ('n', len(nodes))
            nodes.append(key)
        return intern[key]

    def horner(values, bit):
        if bit == 8:
            return ('c', values[0])
        low = horner(values[::2], bit + 1)
        high = horner(values[1::2], bit + 1)
        return expression('xor', low, expression('and', ('b', bit), high))

    root = horner(coeff, 0)
    return nodes, root


def evaluate_circuit(value, nodes, root):
    evaluated = []

    def get(ref):
        kind, index = ref
        return index if kind == 'c' else ((255 if value & (1 << index) else 0)
                                         if kind == 'b' else evaluated[index])

    for op, a, b in nodes:
        evaluated.append(get(a) ^ get(b) if op == 'xor' else get(a) & get(b))
    return get(root)


def generate():
    coeff = coefficients(SBOX)
    nodes, root = circuit(coeff)
    assert [evaluate_byte(x, coeff) for x in range(256)] == list(SBOX)
    assert [evaluate_circuit(x, nodes, root) for x in range(256)] == list(SBOX)

    def rust(ref):
        kind, value = ref
        return f'0x{value * 0x0101010101010101:016x}_u64' if kind == 'c' else f'{kind}{value}'

    lines = ['// Frozen v0.3 S-box: factored vector-valued ANF.',
             '// Generated by research/generate_sbox_circuit.py. Do not edit.',
             f'// {len(nodes)} fixed Boolean gates; eight byte lanes; no lookup table.',
             '// Target-specific assembly review is still required.',
             '#[rustfmt::skip]',
             'pub(crate) fn substitute_word(value: u64) -> u64 {',
             '    const LANES: u64 = 0x0101_0101_0101_0101;']
    for bit in range(8):
        shifted = f'(value >> {bit})' if bit else 'value'
        lines += [f'    let t{bit} = {shifted} & LANES;',
                  f'    let b{bit} = (t{bit} << 8).wrapping_sub(t{bit});']
    for index, (op, a, b) in enumerate(nodes):
        expression = f'{rust(a)} {"^" if op == "xor" else "&"} {rust(b)}'
        lines.append(f'    {expression}' if root == ('n', index) else f'    let n{index} = {expression};')
    if root[0] != 'n':
        lines.append(f'    {rust(root)}')
    lines += ['}', '']
    return '\n'.join(lines), coeff


if __name__ == '__main__':
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    path = ROOT / 'crates/nastyx-engine/src/boolean_substitution.rs'
    content, _ = generate()
    if args.check:
        if path.read_text(encoding='utf8') != content:
            raise SystemExit('Generated circuit differs; regenerate the entire source')
        print('Entire generated circuit and all 256 S-box outputs verified')
    else:
        path.write_text(content, encoding='utf8')
        print('Factored Boolean S-box generated')
