"""Derive a Boolean evaluation of the frozen original S-box. Public coefficients."""
import argparse
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / 'research/reference_cipher'))
from engine_v3 import SBOX


def coefficients(table):
    if len(table) != 256:
        raise ValueError('256 truth-table entries required')
    result = list(table)
    for bit in range(8):
        for mask in range(256):
            if mask & (1 << bit):
                result[mask] ^= result[mask ^ (1 << bit)]
    return result


def evaluate_byte(value, coeff):
    out = 0
    for mask, coefficient in enumerate(coeff):
        if value & mask == mask:
            out ^= coefficient
    return out


TEMPLATE = '''// Boolean ANF of the original frozen v0.3 S-box.
// Generated by research/generate_sbox_circuit.py; no secret-indexed table access.
const COEFFICIENTS: [u8; 256] = [
{coefficients}
];

/// Evaluate all eight byte lanes in parallel. Indices/branches depend only on
/// public loop counters and public coefficients. Machine-code timing still needs
/// target-specific review; this source shape is not a constant-time certification.
pub(crate) fn substitute_word(value: u64) -> u64 {{
    const LANES: u64 = 0x0101_0101_0101_0101;
    let bits: [u64; 8] = std::array::from_fn(|bit| (value >> bit) & LANES);
    let mut terms = [0_u64; 256];
    let mut output = 0_u64;
    terms[0] = LANES;
    for mask in 0_usize..256 {{
        if mask != 0 {{
            let bit = mask.trailing_zeros() as usize;
            terms[mask] = terms[mask & (mask - 1)] & bits[bit];
        }}
        let term = terms[mask];
        let coefficient = COEFFICIENTS[mask];
        // Each term lane is 0 or 1. Multiplication by 255 fills exactly that
        // byte lane; the shift/subtraction spelling avoids secret multiplication.
        let byte_mask = term.wrapping_shl(8).wrapping_sub(term);
        let public_coefficient = u64::from(coefficient).wrapping_mul(LANES);
        output ^= byte_mask & public_coefficient;
    }}
    output
}}
'''


def generate():
    coeff = coefficients(SBOX)
    assert [evaluate_byte(x, coeff) for x in range(256)] == list(SBOX)
    rows = '\n'.join('    ' + ', '.join(map(str, coeff[i:i + 16])) + ',' for i in range(0, 256, 16))
    return TEMPLATE.format(coefficients=rows), coeff


if __name__ == '__main__':
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    path = ROOT / 'crates/nastyx-engine/src/boolean_substitution.rs'
    content, coeff = generate()
    if args.check:
        text = path.read_text(encoding='utf8')
        array = text.split('const COEFFICIENTS: [u8; 256] = [', 1)[1].split('];', 1)[0]
        if list(map(int, re.findall(r'\d+', array))) != coeff:
            raise SystemExit('Boolean coefficients differ')
        print('256 ANF coefficients and all 256 S-box outputs verified')
    else:
        path.write_text(content, encoding='utf8')
        print('Boolean S-box implementation generated')
